  // Procedural BGM: Fun, rhythmic synth pop
  public startBgm() {
    if (this.isMuted || this.bgmInterval) return;
    this.initContext();
    this.bgmStep = 0;
    
    // 130 BPM = ~115ms per 16th note
    const bassScale = [110, 110, 130.81, 146.83, 164.81, 130.81, 146.83, 110];
    const melodyScale = [440, 523.25, 587.33, 659.25, 587.33, 523.25, 659.25, 880];

    this.bgmInterval = window.setInterval(() => {
      if (this.isMuted || !this.ctx) return;
      try {
        const now = this.ctx.currentTime;
        const step = this.bgmStep % 16;
        
        // Bass beat on every 2 steps
        if (step % 2 === 0) {
          const bassFreq = bassScale[(step / 2) % bassScale.length];
          const bassOsc = this.ctx.createOscillator();
          const bassGain = this.ctx.createGain();
          bassOsc.type = 'triangle';
          bassOsc.frequency.setValueAtTime(bassFreq, now);
          bassGain.gain.setValueAtTime(0.08, now);
          bassGain.gain.exponentialRampToValueAtTime(0.001, now + 0.14);
          bassOsc.connect(bassGain);
          bassGain.connect(this.ctx.destination);
          bassOsc.start(now);
          bassOsc.stop(now + 0.15);
        }

        // Melody accent on certain beats
        if (step === 0 || step === 3 || step === 6 || step === 10 || step === 14) {
          const melFreq = melodyScale[(this.bgmStep / 3 | 0) % melodyScale.length];
          const melOsc = this.ctx.createOscillator();
          const melGain = this.ctx.createGain();
          melOsc.type = 'sine';
          melOsc.frequency.setValueAtTime(melFreq, now);
          melGain.gain.setValueAtTime(0.04, now);
          melGain.gain.exponentialRampToValueAtTime(0.001, now + 0.2);
          melOsc.connect(melGain);
          melGain.connect(this.ctx.destination);
          melOsc.start(now);
          melOsc.stop(now + 0.22);
        }

        // Soft hi-hat on every 4th step
        if (step % 4 === 2) {
          const hatOsc = this.ctx.createOscillator();
          const hatGain = this.ctx.createGain();
          hatOsc.type = 'highpass' as unknown as OscillatorType;
          hatOsc.frequency.setValueAtTime(1000, now);
          hatGain.gain.setValueAtTime(0.02, now);
          hatGain.gain.exponentialRampToValueAtTime(0.001, now + 0.05);
          hatOsc.connect(hatGain);
          hatGain.connect(this.ctx.destination);
          hatOsc.start(now);
          hatOsc.stop(now + 0.06);
        }

        this.bgmStep++;
      } catch {
        // ignore
      }
    }, 125);
  }

  public stopBgm() {
    if (this.bgmInterval) {
      clearInterval(this.bgmInterval);
      this.bgmInterval = null;
    }
  }
